/**
 * Resolves the primary authentic product picture URL.
 * @param {Object} product - Product object with name, category, image_url
 * @returns {string} High-resolution image URL
 */
export function getProductImage(product) {
  if (!product) {
    return "https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=900&auto=format&fit=crop&q=85";
  }

  // If backend image_url is a direct valid unsplash image
  if (product.image_url && product.image_url.startsWith("http") && !product.image_url.includes("picsum.photos")) {
    return product.image_url;
  }

  const nameLower = (product.name || "").toLowerCase();

  // Search keyword map
  for (const [key, urls] of Object.entries(PRODUCT_IMAGE_MAP)) {
    if (nameLower.includes(key)) {
      return urls[0];
    }
  }

  // Additional fine-grained keywords
  if (nameLower.includes("jordan") || nameLower.includes("sneaker") || nameLower.includes("shoe")) {
    return "https://images.unsplash.com/photo-1552346154-21d32810aba3?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("drone")) {
    return "https://images.unsplash.com/photo-1508614589041-895b88991e3e?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("chair") || nameLower.includes("desk")) {
    return "https://images.unsplash.com/photo-1580481077195-c266a2e4e13d?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("sofa") || nameLower.includes("couch")) {
    return "https://images.unsplash.com/photo-1555041469-a586c61ea9bc?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("watch")) {
    return "https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("headphone") || nameLower.includes("earphone") || nameLower.includes("audio")) {
    return "https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("laptop") || nameLower.includes("macbook") || nameLower.includes("computer")) {
    return "https://images.unsplash.com/photo-1517336714731-489689fd1ca8?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("phone") || nameLower.includes("galaxy") || nameLower.includes("iphone")) {
    return "https://images.unsplash.com/photo-1610945265064-0e34e5519bbf?w=900&auto=format&fit=crop&q=85";
  }
  if (nameLower.includes("bag") || nameLower.includes("backpack")) {
    return "https://images.unsplash.com/photo-1553062407-98eeb64c6a62?w=900&auto=format&fit=crop&q=85";
  }

  // Fallback to Category Images
  const catList = CATEGORY_FALLBACK_IMAGES[product.category];
  if (catList && catList.length > 0) {
    const idx = Math.abs((product.id || 0) % catList.length);
    return catList[idx];
  }

  return "https://images.unsplash.com/photo-1505740420928-5e560c06d30e?w=900&auto=format&fit=crop&q=85";
}

