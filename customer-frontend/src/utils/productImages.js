/**
 * Resolves the primary authentic product picture URL.
 * @param {Object} product - Product object with name, category, image_url
 * @returns {string} High-resolution image URL
 */
export function getProductImage(product) {
  if (!product) {
    return "https://m.media-amazon.com/images/I/81vxWpPpgNL.jpg";
  }

  // 1. Direct explicit image link if provided by vendor
  if (product.image_url && typeof product.image_url === "string" && product.image_url.trim().length > 5) {
    return product.image_url.trim();
  }

  const nameLower = (product.name || "").toLowerCase();

  // 2. Keyword match against authentic real-world products
  for (const [key, data] of Object.entries(REAL_WORLD_PRODUCTS_DATA)) {
    if (nameLower.includes(key)) {
      return data.primary;
    }
  }

  // 3. Category match fallback
  const catLower = (product.category || "").toLowerCase();
  for (const [catKey, imgUrl] of Object.entries(CATEGORY_DEFAULT_IMAGES)) {
    if (catLower.includes(catKey)) {
      return imgUrl;
    }
  }

  // General fallback
  return "https://m.media-amazon.com/images/I/81vxWpPpgNL.jpg";
}

/**
 * Resolves the source marketplace badge info for the product.
 * @param {Object} product
 * @returns {Object} badge info with label, icon, color, bg
 */
export function getProductSource(product) {
  if (!product) return PRODUCT_SOURCE_BADGES.amazon;
  const nameLower = (product.name || "").toLowerCase();
  const vendorNameLower = (product.vendor_name || (product.vendor && product.vendor.name) || "").toLowerCase();

  if (nameLower.includes("voltx") || vendorNameLower.includes("voltx") || product.vendor_id === 9) {
    return PRODUCT_SOURCE_BADGES.voltx;
  }

  for (const [key, data] of Object.entries(REAL_WORLD_PRODUCTS_DATA)) {
    if (nameLower.includes(key)) {
      const srcKey = (data.source || "amazon").toLowerCase();
      if (srcKey.includes("voltx")) return PRODUCT_SOURCE_BADGES.voltx;
      if (srcKey.includes("flipkart")) return PRODUCT_SOURCE_BADGES.flipkart;
      if (srcKey.includes("google")) return PRODUCT_SOURCE_BADGES.google;
      return PRODUCT_SOURCE_BADGES.amazon;
    }
  }

  // Deterministic source based on product ID
  const idMod = Math.abs((product.id || 0) % 3);
  if (idMod === 1) return PRODUCT_SOURCE_BADGES.flipkart;
  if (idMod === 2) return PRODUCT_SOURCE_BADGES.google;
  return PRODUCT_SOURCE_BADGES.amazon;
}

